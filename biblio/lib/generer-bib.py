#!/usr/bin/env python3
"""Generate a BibTeX file containing entries selected by a YAML mapping."""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Mapping
from pathlib import Path

try:
    import yaml
except ImportError:
    print("error: PyYAML is required (install it with: pip install pyyaml)", file=sys.stderr)
    raise SystemExit(1)


def parse_bibtex(path: Path) -> dict[str, str]:
    """Return BibTeX entries indexed by their citation key."""
    content = path.read_text(encoding="utf-8")
    entries: dict[str, str] = {}
    pattern = re.compile(r"(@\w+\{([^,]+),)", re.MULTILINE)

    for match in pattern.finditer(content):
        start = match.start()
        depth = 0
        index = content.find("{", start)
        end = None
        while index < len(content):
            char = content[index]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    end = index
                    break
            index += 1
        if end is not None:
            key = match.group(2).strip()
            entries[key] = content[start : end + 1]
    return entries


def add_number(entry: str, number: int) -> str:
    """Insert or replace the number field in a BibTeX entry."""
    entry = re.sub(r"\n[ \t]*number[ \t]*=[ \t]*\{[^}]*\},?", "", entry)
    return re.sub(
        r"(@\w+\{[^,]+,)",
        rf"\1\n\tnumber = {{{number}}},",
        entry,
        count=1,
    )


def load_mapping(path: Path) -> dict[str, int]:
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, yaml.YAMLError) as exc:
        raise ValueError(f"cannot read YAML mapping '{path}': {exc}") from exc

    if not isinstance(data, Mapping):
        raise TypeError(f"'{path}' must contain a mapping of string keys to numbers")

    result: dict[str, int] = {}
    for key, number in data.items():
        if not isinstance(key, str):
            raise TypeError(f"'{path}' contains a non-string reference key: {key!r}")
        if isinstance(number, bool) or not isinstance(number, int):
            raise TypeError(f"'{path}' must map each string key to an integer")
        if number < 0:
            raise ValueError(f"'{path}' must map each string key to a non-negative integer")
        result[key] = number
    return result


def default_output_path(bibtex_path: Path) -> Path:
    return bibtex_path.with_name(f"{bibtex_path.stem}-numbered.bib")


def generate(bibtex_path: Path, yml_path: Path, output_path: Path) -> int:
    if not bibtex_path.is_file():
        print(f"error: BibTeX file not found: {bibtex_path}", file=sys.stderr)
        return 1
    if not yml_path.is_file():
        print(f"error: YAML file not found: {yml_path}", file=sys.stderr)
        return 1
    if bibtex_path.resolve() == output_path.resolve():
        print("error: output file must be different from the input BibTeX file", file=sys.stderr)
        return 2

    try:
        mapping = load_mapping(yml_path)
        entries = parse_bibtex(bibtex_path)
    except (OSError, UnicodeDecodeError, TypeError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    lines = [
        f"% Generated from {bibtex_path} and {yml_path}.",
        "% Do not edit this file by hand.",
        "",
    ]
    missing: list[str] = []
    for key, number in mapping.items():
        entry = entries.get(key)
        if entry is None:
            missing.append(key)
            continue
        lines.extend((add_number(entry, number), ""))

    try:
        output_path.write_text("\n".join(lines), encoding="utf-8")
    except OSError as exc:
        print(f"error: cannot write '{output_path}': {exc}", file=sys.stderr)
        return 1

    print(f"{output_path} generated ({len(mapping) - len(missing)} entries).")
    if missing:
        print(f"warning: {len(missing)} key(s) not found in {bibtex_path}:", file=sys.stderr)
        for key in missing:
            print(f"  - {key}", file=sys.stderr)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Build a numbered BibTeX file from a BibTeX source and YAML key-to-number mapping.",
        epilog=(
            "The default output is <bibtex-name>-numbered.bib. "
            "Calling bibyml2bib with no arguments retains the legacy _pieces-*.yml batch mode."
        ),
    )
    parser.add_argument("bibtex_file", type=Path, help="Source BibTeX file (first positional argument)")
    parser.add_argument("yml", type=Path, help="YAML mapping of string keys to numbers (second positional argument)")
    parser.add_argument(
        "-o",
        "--output-file",
        type=Path,
        help="Output BibTeX file (default: <bibtex-name>-numbered.bib)",
    )
    args = parser.parse_args()
    output_path = args.output_file or default_output_path(args.bibtex_file)
    return generate(args.bibtex_file, args.yml, output_path)


if __name__ == "__main__":
    raise SystemExit(main())
