#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: refresh.sh [-h|--help]

Refresh user-level group/command and shortcut wrappers, Fish completion, and
man pages. Mutable generated files are written under the user's Linto data
directory; the installation tree is read-only.
EOF
}

case "${1-}" in
  -h|--help) usage; exit 0 ;;
  '') ;;
  *) usage >&2; exit 2 ;;
esac

root=$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)
case "${XDG_DATA_HOME:-}" in
  /*) data_home=$XDG_DATA_HOME ;;
  *) data_home=$HOME/.local/share ;;
esac
linto_data_dir="$data_home/linto"
user_bin_dir="$linto_data_dir/bin"
completion_dir="$linto_data_dir/completions"
man_topics_dir="$linto_data_dir/man/man1"
man_page="$man_topics_dir/linto.1"
config="$root/config.yml"
config_tool="$root/lib/config.py"
guide_dir="$root/linto-guide"
bin_dir="$root/bin"
linto="$bin_dir/linto"
wrapper_dir="$user_bin_dir/.generated-wrappers"
owned="$wrapper_dir/owned"

[[ -x "$linto" ]] || { printf 'refresh: dispatcher not executable: %s\n' "$linto" >&2; exit 1; }
[[ -f "$config" && -f "$config_tool" ]] || { printf 'refresh: config or config helper is missing\n' >&2; exit 1; }
if ! command -v mandown >/dev/null 2>&1; then
  printf 'refresh: mandown is required to generate topic man pages (run linto linto mdsetup)\n' >&2
  exit 1
fi
if ! command -v groff >/dev/null 2>&1; then
  printf 'refresh: groff is required to validate topic man pages\n' >&2
  exit 1
fi
[[ -d "$root/linto-guide" ]] || { printf 'refresh: guide directory not found: %s\n' "$root/linto-guide" >&2; exit 1; }

mapfile -t groups < <("$linto" --list-groups)
mapfile -t shortcut_aliases < <("$linto" --list-shortcut-aliases)
declare -a names=() groups_for_stub=() commands_for_stub=() kinds=()
declare -A desired=()

add_stub() {
  local name=$1 group=$2 command=$3 kind=$4
  [[ -z "${desired[$name]+yes}" ]] || {
    printf 'refresh: generated wrapper name collision: %s\n' "$name" >&2
    exit 1
  }
  names+=("$name")
  groups_for_stub+=("$group")
  commands_for_stub+=("$command")
  kinds+=("$kind")
  desired["$name"]=1
}

for group in "${groups[@]}"; do
  add_stub "linto-$group" "$group" '' group
  mapfile -t commands < <("$linto" --list-commands "$group")
  for command in "${commands[@]}"; do
    case "$group/$command" in
      linto/addgroup|linto/rmgroup|linto/refresh|linto/setup) continue ;;
    esac
    add_stub "linto-$group-$command" "$group" "$command" group-command
  done
done

for alias_entry in "${shortcut_aliases[@]}"; do
  IFS=$'\t' read -r shortcut group command <<< "$alias_entry"
  [[ -n "$shortcut" ]] || continue
  add_stub "linto-$shortcut" "$group" "$command" shortcut-alias
done

mkdir -p -- "$wrapper_dir" "$completion_dir" "$man_topics_dir"

write_stub() {
  local dest=$1 group=$2 command=$3 kind=$4
  {
    printf '%s\n' '#!/bin/sh'
    case "$kind" in
      group) printf 'exec %q %q "$@"\n' "$linto" "$group" ;;
      group-command|shortcut-alias)
        printf 'exec %q %q %q "$@"\n' "$linto" "$group" "$command"
        ;;
    esac
  } > "$dest"
  chmod 755 "$dest"
}

# Validate existing destinations before changing any generated files.
for index in "${!names[@]}"; do
  name=${names[$index]}
  dest="$user_bin_dir/$name"
  [[ -e "$dest" || -L "$dest" ]] || continue
  [[ -f "$dest" && ! -L "$dest" ]] || {
    printf 'refresh: refusing to replace non-file path: %s\n' "$dest" >&2
    exit 1
  }
  expected_head='#!/bin/sh'
  if [[ "${kinds[$index]}" == group ]]; then
    printf -v expected_exec 'exec %q %q "$@"' "$linto" "${groups_for_stub[$index]}"
  else
    printf -v expected_exec 'exec %q %q %q "$@"' "$linto" \
      "${groups_for_stub[$index]}" "${commands_for_stub[$index]}"
  fi
  if ! grep -Fqx "$expected_head" "$dest" ||
     ! grep -Fqx "$expected_exec" "$dest"; then
    printf 'refresh: refusing to replace unrecognized path: %s\n' "$dest" >&2
    exit 1
  fi
done

# Remove only paths recorded as generated by a previous refresh.
if [[ -f "$owned" ]]; then
  while IFS= read -r old_name; do
    [[ -n "$old_name" ]] || continue
    [[ -n "${desired[$old_name]+yes}" ]] || rm -f -- "$user_bin_dir/$old_name"
  done < "$owned"
fi

for index in "${!names[@]}"; do
  write_stub "$user_bin_dir/${names[$index]}" "${groups_for_stub[$index]}" \
    "${commands_for_stub[$index]}" "${kinds[$index]}"
done
printf '%s\n' "${names[@]}" | LC_ALL=C sort -u > "$wrapper_dir/owned.tmp"
mv -- "$wrapper_dir/owned.tmp" "$owned"

{
  printf "set -g linto_bin '%s'\n" "$linto"
  cat <<'FISH_HEADER'
complete -c linto -f -n '__fish_use_subcommand' -a 'help completion'
complete -c linto -f -n '__fish_use_subcommand' -a '($linto_bin --list-groups 2>/dev/null)'
complete -c linto -f -n '__fish_use_subcommand' -a '($linto_bin --list-shortcuts 2>/dev/null)'
complete -c linto -f -n '__fish_seen_subcommand_from completion' -a 'bash zsh fish'
FISH_HEADER
} > "$completion_dir/linto.fish"
for group in "${groups[@]}"; do
  cat >> "$completion_dir/linto.fish" <<EOF
complete -c linto -f -n '__fish_seen_subcommand_from $group linto-$group' -a '(\$linto_bin --list-commands $group 2>/dev/null)'

EOF
done
cat >> "$completion_dir/linto.fish" <<'FISH_FOOTER'
complete -c linto -f -n '__fish_seen_subcommand_from help' -a '($linto_bin --list-groups 2>/dev/null)'
complete -c linto -f -n '__fish_seen_subcommand_from help' -a '($linto_bin --list-shortcuts 2>/dev/null)'
complete -c linto -l help -s h -d 'Show help'
FISH_FOOTER

man_tmp=$(mktemp "$man_topics_dir/.linto.1.XXXXXX")
trap 'rm -f -- "$man_tmp"' EXIT
python3 - "$root/man/linto.1" "${groups[@]}" > "$man_tmp" <<'PY'
from pathlib import Path
import sys
path = Path(sys.argv[1])
groups = sys.argv[2:]
text = path.read_text()
start = '.\\" BEGIN GENERATED GROUPS'
end = '.\\" END GENERATED GROUPS'
if text.count(start) != 1 or text.count(end) != 1:
    raise SystemExit('refresh: expected one generated-groups marker pair')
a = text.index(start) + len(start)
b = text.index(end)
if b < a:
    raise SystemExit('refresh: generated-groups markers are reversed')
lines = []
for i, group in enumerate(groups):
    lines.append(f'.BR {group} ' + (' ,' if i < len(groups) - 1 else ' .'))
    if i == len(groups) - 2:
        lines.append('and')
sys.stdout.write(text[:a] + '\n' + '\n'.join(lines) + '\n' + text[b:])
PY
mkdir -p -- "$man_topics_dir"

topic_tmp=$(mktemp -d "$man_topics_dir/.topics.XXXXXX")
trap 'rm -rf -- "$topic_tmp"' EXIT

declare -A desired_topics=()
for source in "$guide_dir"/*.md; do
  [[ -f "$source" ]] || continue
  topic=${source##*/}
  topic=${topic%.md}
  case "$topic" in
    *[!a-zA-Z0-9_-]*|'')
      printf 'refresh: invalid guide topic filename: %s\n' "$source" >&2
      exit 1
      ;;
  esac
  dest="$man_topics_dir/linto-$topic.1"
  [[ ! -e "$dest" || -f "$dest" ]] || {
    printf 'refresh: refusing to replace non-file path: %s\n' "$dest" >&2
    exit 1
  }
  desired_topics["linto-$topic.1"]=1

  preprocessed="$topic_tmp/$topic.md"
  roff_tmp="$topic_tmp/linto-$topic.1"
  python3 - "$source" "$preprocessed" <<'PY'
from pathlib import Path
import re, sys
source, output = map(Path, sys.argv[1:])
text = source.read_text()
# Mermaid diagrams do not have a meaningful plain-text man-page rendering.
text = re.sub(r"```mermaid\s*\n.*?^```\s*$", "", text, flags=re.M | re.S)
# Convert fenced examples to indented Markdown; mandown preserves those as
# no-fill blocks with line breaks intact.
def code_block(match):
    body = match.group(1).rstrip("\n")
    return "\n".join("    " + line if line else "" for line in body.splitlines())
text = re.sub(r"```[^\n]*\n(.*?)^```\s*$", code_block, text, flags=re.M | re.S)
# mandown treats inline code and Markdown link targets awkwardly. Keep the
# visible text while avoiding literal backticks and reference footnotes.
text = re.sub(r"`([^`]+)`", r"**\1**", text)
text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
output.write_text(text)
PY
  title=$(printf '%s' "$topic" | tr '[:lower:]_-' '[:upper:]__')
  mandown "$preprocessed" "LINTO-$title" 1 > "$roff_tmp"
  groff -Wall -man -Tutf8 "$roff_tmp" > /dev/null
done

# Install only after all generated pages have passed groff validation.
for generated in "$topic_tmp"/linto-*.1; do
  [[ -f "$generated" ]] || continue
  install -m 0644 -- "$generated" "$man_topics_dir/${generated##*/}"
done
for existing in "$man_topics_dir"/linto-*.1; do
  [[ -f "$existing" ]] || continue
  name=${existing##*/}
  [[ -n "${desired_topics[$name]+yes}" ]] || rm -f -- "$existing"
done
mv -- "$man_tmp" "$man_page"

printf 'Refreshed %d active group(s), wrappers, completions, dispatcher man page, and %d guide topic man page(s).\n' \
  "${#groups[@]}" "${#desired_topics[@]}"
