#!/usr/bin/env python3
"""Generate a BibTeX file containing entries selected by a YAML mapping."""

from __future__ import annotations

import re
import sys
from collections.abc import Mapping
from pathlib import Path

import cli
from cli import _

try:
    import yaml
except ImportError:
    raise SystemExit(f"bibyml2bib: {_('PyYAML is required (install it with: pip install pyyaml)')}")


def parse_bibtex(path: Path) -> dict[str, str]:
    """Return BibTeX entries indexed by their citation key."""
    content = path.read_text(encoding="utf-8")
    entries: dict[str, str] = {}
    pattern = re.compile(r"(@\w+\{([^,]+),)", re.MULTILINE)

    for match in pattern.finditer(content):
        start = match.start()
        depth = 0
        index = content.find("{", start)
        end = None
        while index < len(content):
            char = content[index]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    end = index
                    break
            index += 1
        if end is not None:
            key = match.group(2).strip()
            entries[key] = content[start : end + 1]
    return entries


def add_number(entry: str, number: int) -> str:
    """Insert or replace the number field in a BibTeX entry."""
    entry = re.sub(r"\n[ \t]*number[ \t]*=[ \t]*\{[^}]*\},?", "", entry)
    return re.sub(
        r"(@\w+\{[^,]+,)",
        rf"\1\n\tnumber = {{{number}}},",
        entry,
        count=1,
    )


def load_mapping(path: Path) -> dict[str, int]:
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, yaml.YAMLError) as exc:
        raise ValueError(f"cannot read YAML mapping '{path}': {exc}") from exc

    if not isinstance(data, Mapping):
        raise TypeError(f"'{path}' must contain a mapping of string keys to numbers")

    result: dict[str, int] = {}
    for key, number in data.items():
        if not isinstance(key, str):
            raise TypeError(f"'{path}' contains a non-string reference key: {key!r}")
        if isinstance(number, bool) or not isinstance(number, int):
            raise TypeError(f"'{path}' must map each string key to an integer")
        if number < 0:
            raise ValueError(f"'{path}' must map each string key to a non-negative integer")
        result[key] = number
    return result


STDIN = Path("/dev/stdin")


def generate(bibtex_path: Path, yml_path: Path, output_path: Path | None) -> int:
    if bibtex_path != STDIN and not bibtex_path.is_file():
        cli.fail("bibyml2bib", _("BibTeX file not found: {}").format(bibtex_path))
        return 1
    if not yml_path.is_file():
        cli.fail("bibyml2bib", _("YAML file not found: {}").format(yml_path))
        return 1
    if output_path is not None and bibtex_path != STDIN and bibtex_path.resolve() == output_path.resolve():
        cli.fail("bibyml2bib", _("output file must be different from the input BibTeX file"))
        return 2

    try:
        mapping = load_mapping(yml_path)
        entries = parse_bibtex(bibtex_path)
    except (OSError, UnicodeDecodeError, TypeError, ValueError) as exc:
        cli.fail("bibyml2bib", str(exc))
        return 1

    lines = [
        f"% Generated from {bibtex_path} and {yml_path}.",
        "% Do not edit this file by hand.",
        "",
    ]
    missing: list[str] = []
    for key, number in mapping.items():
        entry = entries.get(key)
        if entry is None:
            missing.append(key)
            continue
        lines.extend((add_number(entry, number), ""))

    try:
        if output_path is None:
            sys.stdout.write("\n".join(lines))
        else:
            output_path.write_text("\n".join(lines), encoding="utf-8")
    except OSError as exc:
        cli.fail("bibyml2bib", _("cannot write '{}': {}").format(output_path, exc))
        return 1

    if output_path is not None:
        print(_("{} generated ({} entries).").format(output_path, len(mapping) - len(missing)), file=sys.stderr)
    if missing:
        print(_("warning: {} key(s) not found in {}:").format(len(missing), bibtex_path), file=sys.stderr)
        for key in missing:
            print(f"  - {key}", file=sys.stderr)
    return 0


def main() -> int:
    parser = cli.Parser(
        "bibyml2bib",
        _("Build a numbered BibTeX file from a BibTeX source and YAML key-to-number mapping."),
        epilog=(
            _("The default output is standard output; the source BibTeX may be - for stdin. "
              "Calling bibyml2bib with no arguments retains the legacy _pieces-*.yml batch mode.")
        ),
    )
    parser.add_argument("bibtex_file", type=Path, metavar=_("source.bib"), help=_("Source BibTeX file (first positional argument)"))
    parser.add_argument("yml", type=Path, metavar=_("mapping.yml"), help=_("YAML mapping of string keys to numbers (second positional argument)"))
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        help=_("Output BibTeX file (default: standard output)"),
    )
    args = parser.parse_args()
    bibtex_path = STDIN if str(args.bibtex_file) == "-" else args.bibtex_file
    output_path = None if args.output is None or str(args.output) == "-" else args.output
    return generate(bibtex_path, args.yml, output_path)


if __name__ == "__main__":
    raise SystemExit(main())
